'use client';

import { apiFetch } from '@/lib/api-client';
import { useEffect, useState } from 'react';
import HeaderAndSearch from '../_components/UI/HeaderAndSearch';
import ReportsTable from '../_components/UI/ReportsTable';
import { Report } from '@/types/reports';
import { exportAllReportsToPDF } from '@/utils/exportAllReportsToPDF';

const Reports = () => {
    const [reports, setReports] = useState<Report[]>([]);
    const [loading, setLoading] = useState(true);
    const [searchTerm, setSearchTerm] = useState('');

    useEffect(() => {
        const fetchReports = async () => {
            try {
                const response = await apiFetch('/api/academy/mobile/admin/reports');
                const result = (await response.json()) as { reports: Report[] };
                setReports(
                    result.reports.map((report) => ({
                        ...report,
                        reportedAt: report.reportedAt
                            ? new Date(report.reportedAt).toLocaleString()
                            : '',
                    })),
                );
            } catch (error) {
                console.error('Error fetching reports:', error);
            } finally {
                setLoading(false);
            }
        };

        fetchReports();
    }, []);

    const handleExportPDF = () => {
        exportAllReportsToPDF(reports, {
            fileName: 'reports.pdf',
            title: 'All Reports',
            subtitle: 'Generated by CheFu Academy Admin Panel',
            logoUrl: '/logo.png', // Optional – local/public image or base64 data URL
        });
    };

    return (
        <div className=" md:p-6">
            <HeaderAndSearch
                searchTerm={searchTerm}
                setSearchTerm={setSearchTerm}
                handleExportPDF={handleExportPDF}
            />

            {/* Reports Table */}
            <ReportsTable reports={reports} loading={loading} />
        </div>
    );
};

export default Reports;
